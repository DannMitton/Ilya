const mark = (art: readonly string[]): Mark => {
	const h = art.length;
	const w = art[0].length;
	const mask = new Uint8Array(w * h);
	art.forEach((row, y) => [...row].forEach((c, x) => (mask[y * w + x] = c === '#' ? 1 : 0)));
	return { x0: 0, y0: 0, x1: w - 1, y1: h - 1, mask };
};
const reads = (art: readonly string[], space: number) => isThree(shapeOf(mark(art)), art.length / space);

describe('the shape of a printed 3', () => {
	it('reads the 3 of two engravings', () => {
		expect(reads(JURGENSON_3, 28)).toBe(true);
		expect(reads(MUSSORGSKY_3, 30)).toBe(true);
	});

	it('does not read a letter of a sung word or a bracket end as a 3', () => {
		expect(reads(LETTER_K, 29)).toBe(false);
		expect(reads(LETTER_U, 30)).toBe(false);
		expect(reads(BRACKET_HOOK, 29)).toBe(false);
	});

	it('does not read a 3 shorter than a staff space', () => {
		expect(reads(JURGENSON_3, 41)).toBe(false);
	});

	it('does not read the 3 mirrored, which closes on the left', () => {
		expect(reads(JURGENSON_3.map((r) => [...r].reverse().join('')), 28)).toBe(false);
	});
});

/** A white page with a staff (five lines, `space` apart, from `top`) and a mark pasted at (x, y). */
function page(space: number, top: number, marks: { art: readonly string[]; x: number; y: number }[]): GreyPage {
	const width = 900;
	const height = 900;
	const data = new Uint8Array(width * height).fill(255);
	for (let l = 0; l < 5; l++) for (let x = 40; x < width - 40; x++) for (let t = 0; t < 3; t++) data[(top + l * space + t) * width + x] = 0;
	for (const m of marks) m.art.forEach((row, y) => [...row].forEach((c, x) => c === '#' && (data[(m.y + y) * width + m.x + x] = 0)));
	return { width, height, data };
}
const NOTES = [{ x: 380, y: 340 }, { x: 450, y: 352 }, { x: 520, y: 340 }];

describe('lookForTupletNumber', () => {
	it('finds the 3 printed under the middle note of the group', () => {
		const p = page(28, 300, [{ art: JURGENSON_3, x: 434, y: 440 }]);
		expect(lookForTupletNumber(p, NOTES).number).toBe(3);
	});

	it('finds nothing where nothing is printed, and says no mark stood there', () => {
		const looked = lookForTupletNumber(page(28, 300, []), NOTES);
		expect(looked.number).toBeNull();
		expect(looked.candidates).toBe(0);
	});

	it('does not take a 3 printed over a neighbouring group', () => {
		const p = page(28, 300, [{ art: JURGENSON_3, x: 600, y: 440 }]);
		expect(lookForTupletNumber(p, NOTES).number).toBeNull();
	});

	it('does not take a 3-shaped mark that stands in a word (a letter з beside a)', () => {
		const p = page(28, 300, [
			{ art: JURGENSON_3, x: 434, y: 440 },
			{ art: JURGENSON_3.map((r) => [...r].reverse().join('')), x: 470, y: 440 },
		]);
		expect(lookForTupletNumber(p, NOTES).number).toBeNull();
	});
});
