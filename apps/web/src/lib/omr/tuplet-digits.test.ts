export const maskOf = (art: readonly string[]): MarkMask => {
	const height = art.length;
	const width = art[0].length;
	const mask = new Uint8Array(width * height);
	art.forEach((row, y) => [...row].forEach((c, x) => (mask[y * width + x] = c === '#' ? 1 : 0)));
	return { width, height, mask };
};
const TEMPLATES = unpack(packed as PackedTemplate[]);

describe('the digit reader', () => {
	it('counts the loops a digit closes', () => {
		expect(holesOf(maskOf(BRAVURA_5))).toBe(0);
		expect(holesOf(maskOf(['#####', '#...#', '#####']))).toBe(1);
	});

	it('takes the slant out of a mark', () => {
		const slanted = ['...##', '..##.', '.##..', '##...'];
		expect(upright(maskOf(slanted)).width).toBeLessThan(5);
	});

	it('reads Bravura\'s 5, 7, 1, and 2', () => {
		expect(readDigit(maskOf(BRAVURA_5), TEMPLATES).digit).toBe('5');
		expect(readDigit(maskOf(BRAVURA_7), TEMPLATES).digit).toBe('7');
		expect(readDigit(maskOf(BRAVURA_1), TEMPLATES).digit).toBe('1');
		expect(readDigit(maskOf(BRAVURA_2), TEMPLATES).digit).toBe('2');
	});

	it('gives no digit where the nearest mark that is not a digit is as near', () => {
		const f = featuresOf(maskOf(BRAVURA_5));
		const only = [{ ...f, label: '5' }, { ...f, label: '-' }];
		expect(readDigit(maskOf(BRAVURA_5), only).digit).toBeNull();
	});

	it('gives no digit to a mark that is near no digit', () => {
		const block = maskOf(Array.from({ length: 40 }, () => '#'.repeat(30)));
		expect(readDigit(block, TEMPLATES).digit).toBeNull();
	});

	it('never compares marks with different numbers of loops', () => {
		const a = { ...featuresOf(maskOf(BRAVURA_5)) };
		expect(distance(a, { ...a, holes: 1 })).toBe(Number.POSITIVE_INFINITY);
	});
});
