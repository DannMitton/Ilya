/**
 * underlay-widths.ts
 *
 * Measured glyph advance widths for the two faces used in the Cyrillic /
 * IPA "underlay" text printed beneath each notehead, expressed as
 * units-per-em normalised to 1000 (i.e. "per-mille" widths, the same
 * convention OpenType/CSS font metrics use). This lets the renderer -
 * which is pure, DOM-free, and cannot call measureText/getBBox at
 * runtime - estimate real string widths from a static table instead of
 * a flat `s.length * constant` guess.
 *
 * WARNING: these are per-glyph ADVANCE WIDTHS with no kerning applied.
 * Real text is very slightly narrower than the sum of advances once
 * kerning pairs are involved. Lato IPA and Source Serif 4 do not lean
 * on kerning for the character sets used here, so the error this
 * introduces is small, but it is not zero. Do not treat these numbers
 * as pixel-perfect; treat them as "close enough to size a column".
 *
 * Measured from:
 *
 *   - Lato IPA (subset), the IPA underlay face, rendered at 12px.
 *     File: apps/web/static/fonts/lato-ipa.woff2 (bundled with the app).
 *     unitsPerEm = 2000. cmap contains 607 usable code points
 *     (Basic Latin, Latin-1 Supplement, Latin Extended-A, IPA
 *     Extensions, Spacing Modifier Letters, Combining Diacritical
 *     Marks). U+0000 (a null placeholder glyph with 0 advance) is
 *     present in the font's cmap but is not a real character and is
 *     excluded from this table.
 *
 *   - Source Serif 4 (variable font, wght axis pinned to 400/Regular,
 *     upright), the Cyrillic underlay face, rendered at 12.5px. This
 *     font is not bundled; it is loaded from Google Fonts at runtime
 *     the same way the app loads it (app.html requests
 *     `family=Source+Serif+4:ital,opsz,wght@0,8..60,400;...`, a
 *     variable font with an `opsz` (optical size) axis spanning 8-60
 *     that the browser resolves from the rendered font-size). The
 *     *first* pass of this measurement used the static default
 *     instance (opsz defaults to 20 in that file) and was WRONG: optical
 *     size changes advance widths, small opsz is wider than the
 *     default instance, and measuring the default instance therefore
 *     systematically UNDERESTIMATED Cyrillic width at the 12.5px this
 *     text actually renders at - exactly the failure mode the max-based
 *     fallback below exists to avoid. This table is now measured
 *     correctly, from the variable font pinned to `opsz=12.5,
 *     wght=400` via fonttools `varLib.instancer`:
 *       CSS: https://fonts.googleapis.com/css2?family=Source+Serif+4:ital,opsz,wght@0,8..60,200..900&display=swap
 *         (requested with a modern-Chrome User-Agent string, which is
 *         required for Google Fonts to serve the variable woff2
 *         rather than a static per-weight instance)
 *       cyrillic-range variable file (Cyrillic letters, space,
 *       combining acute):
 *         https://fonts.gstatic.com/s/sourceserif4/v14/vEFI2_tTDB4M7-auWDN0ahZJW1gf8tenXg.woff2
 *       latin-range variable file (hyphen-minus, comma, full stop -
 *       these are outside that file's unicode-range so the browser,
 *       and this measurement, pull them from the Latin subset file
 *       instead):
 *         https://fonts.gstatic.com/s/sourceserif4/v14/vEFI2_tTDB4M7-auWDN0ahZJW1gb8tc.woff2
 *     Both instanced to opsz=12.5/wght=400 (`fvar` axes found: wght
 *     200-900 default 400, opsz 8-60 default 20). unitsPerEm = 1000
 *     post-instancing. Table covers the Russian alphabet (А-Я, а-я, Ё,
 *     ё), space, comma, full stop, hyphen-minus, and the combining
 *     acute accent (U+0301, advance 0 - it renders as a mark over the
 *     preceding letter and contributes no pen advance).
 *
 *     CAVEAT: because this table is pinned to opsz=12.5, it is
 *     specific to that rendered size. If this same table is ever
 *     reused for Cyrillic text rendered at a much larger font size
 *     (opsz tracks font-size in the variable font, so a much bigger
 *     size would resolve a larger opsz instance, which is narrower
 *     per em than this one), the widths here will run slightly
 *     narrow. Re-instance at the new opsz if that ever happens; do not
 *     just rescale these numbers.
 *
 * All widths were read from each font's `hmtx` table via fonttools
 * (advance / unitsPerEm * 1000, rounded to the nearest integer), not
 * estimated or guessed.
 */

