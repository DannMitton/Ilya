export const SH_LEMMAS: ReadonlySet<string> = new Set(['пшют']);

/** The shape of `GraysonEngine.lookupStress()`'s result that this module reads. */
export interface LemmaLookup {
  lemma?: string;
  isHomograph?: boolean;
  allEntries?: Array<{ lemma?: string; l?: string }>;
}

/** Dictionary lemmas of a looked-up word: every entry's for a homograph, none for an unknown word. */
export function lemmasOf(lookup: LemmaLookup | null): string[] {
  if (!lookup) return [];
  if (lookup.isHomograph && Array.isArray(lookup.allEntries)) {
    return lookup.allEntries.map((e) => e.lemma ?? e.l ?? '').filter(Boolean);
  }
  return lookup.lemma ? [lookup.lemma] : [];
}

/**
 * Character indices, in the lowercased word, of consonants that palatalize
 * lexically. `lookup` is the word's dictionary lookup.
 */
export function lexicalSoftIndices(word: string, lookup: LemmaLookup | null): number[] {
  const chars = [...word.toLowerCase()];
  const lower = lemmasOf(lookup).map((l) => l.toLowerCase());
  const indices = new Set<number>();

  // -ция, -ционн-: the ц of the suffix, the last ц before и (pp. 283-284).
  if (lower.some((l) => TS_SUFFIX_LEMMAS.has(l) || TS_SUFFIX_ADJECTIVE_LEMMAS.has(l))) {
    for (let i = chars.length - 2; i >= 0; i--) {
      if (chars[i] === 'ц' && chars[i + 1] === 'и') {
        indices.add(i);
        break;
      }
    }
  }

  // цвет: ц in the cluster цв before е or ё (p. 168).
  if (lower.some((l) => TS_TSVET_LEMMAS.has(l))) {
    for (let i = 0; i < chars.length - 2; i++) {
      if (chars[i] === 'ц' && chars[i + 1] === 'в' && (chars[i + 2] === 'е' || chars[i + 2] === 'ё')) {
        indices.add(i);
      }
    }
  }

  // пшют: п and ш (p. 163).
  if (lower.some((l) => SH_LEMMAS.has(l))) {
    for (let i = 0; i < chars.length - 1; i++) {
      if (chars[i] === 'п' && chars[i + 1] === 'ш') {
        indices.add(i);
        indices.add(i + 1);
      }
    }
  }

  return [...indices].sort((a, b) => a - b);
}
