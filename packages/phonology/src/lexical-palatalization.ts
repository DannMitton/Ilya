/**
 * Lexical palatalization of the always-hard consonants ц and ш
 * (Grayson, Russian Lyric Diction, 2012).
 *
 * ц and ш never palatalize by rule (pp. 163, 166). Grayson names the words
 * where they do, and this module carries those words as lemma lists, so the
 * engine adds no new phonological predicate: a word is softened only when its
 * dictionary lemma is listed here.
 *
 *   ш, p. 163: one word, пшют ("fop", obsolete), and its forms: /pʲʃʲut/.
 *     The п is palatalized too, as printed.
 *   ц, p. 168: цвет and its derivatives, "within the cluster" [tʲsʲvʲ] before
 *     е or ё: цвет /tʲsʲvʲɛt/, цветок, расцветать /rɑsʲ tʲsʲvʲɪ ˈtɑtʲ/.
 *   ц, pp. 283-284: the suffix -ция "only when it is analogous to the English
 *     suffixes -tion or -ence", with и kept as [i]; -ция "analogous to the
 *     English suffix -ture, as in лекция" keeps the normal rules. The
 *     adjectival -ционный is soft as "analogous to the English -tial, -tory,
 *     or -tionary".
 *   ц, p. 168: proper names with я, ю, or ё after ц MAY palatalize, "though
 *     [the hard form] is fine, too". Ilya keeps them hard (Dann, 2026-09-27).
 *
 * Palatalized ц prints as tʲsʲ: Grayson's form without his tie bar, which the
 * project's notation excludes (Dann, 2026-09-27).
 *
 * How the lists were sorted (desk, 2026-09-27, dictionary 86d83340), by the
 * FORM of the suffix, as p. 284 sorts them, never by what the word means:
 *   -ция: soft when an English word of the same Latin root ends in -tion,
 *     -sion, -ence, or -ance (-ency and -ancy counted with them), whatever
 *     the Russian word means: репетиция (repetition), дирекция (direction).
 *     Hard when the twin ends otherwise (лекция, lecture) or there is no such
 *     twin (полиция, юстиция, грация, place names, Latin botanical names).
 *     A compound follows its head noun: гидростанция follows станция.
 *   -ционн-: soft when its -ция noun is soft by the noun test, or when an
 *     English adjective of the same root ends in -tial, -tory, -tionary, or
 *     -tional; hard otherwise (инвестиционный). "-tional" is the desk's
 *     documented reading of p. 284, which names only -tial, -tory, and
 *     -tionary (desk, 2026-09-27).
 *   цвет: every lemma whose forms spell цве or цвё, all of them the цвет
 *     root, surnames and botanical names included.
 *
 * NOT RULED, left as they were before the p. 284 re-sort, for Dann:
 *   Unsure the twin shares the root, or the twin is rare:
 *     аукционный (auctionary (archaic))
 *     кассационный (cassational? (rare))
 *     мультипликационный (multiplicational? (rare))
 *     провокационный (provocatory (rare))
 *     экзаменационный (examinatory (rare))
 *     эксплуатационный (exploitatory (rare))
 *     -ция, currently hard: иррумация (irrumation, rare), фелляция (fellation,
 *     rare), инвестиция (investiture, -ture; investition, rare), квитанция
 *     (quittance, rare), комплектация (no clear twin), комплекция (complexion),
 *     конспирация (conspiration, rare; conspiracy), метисация (no clear twin),
 *     рация (a clipping of радиостанция, not the suffix).
 *     -ция, currently soft: экранизация (no English twin), цифровизация
 *     (digitization, another root), китаизация (sinicization, another root),
 *     прихватизация and могилизация (puns on приватизация and мобилизация),
 *     детализация, дискредитация, регламентация, констатация, сигнализация,
 *     реструктуризация, инвентаризация (twins in -ation exist but are rare),
 *     дотация (dotation).
 */

