import { raise } from './raise.mjs';
const { browser, page } = await raise({ width: 1400, height: 900 });
const hb = async () => JSON.stringify(await page.locator('.loupe-header').boundingBox());
const h0 = await page.locator('.loupe-header').boundingBox();
const grab = { x: h0.x + 40, y: h0.y + 20 };
await page.mouse.move(grab.x, grab.y); await page.mouse.down();
await page.mouse.move(grab.x + 2000, grab.y - 200, { steps: 5 }); await page.mouse.up();
console.log('dragged far right and up: header', await hb());
await page.setViewportSize({ width: 1000, height: 700 });
await page.waitForTimeout(800);
console.log('after resize to 1000x700: header', await hb());
await page.setViewportSize({ width: 1400, height: 900 });
await page.waitForTimeout(500);
await page.mouse.move(grab.x, grab.y);
const h1 = await page.locator('.loupe-header').boundingBox();
await page.mouse.move(h1.x + 40, h1.y + 20); await page.mouse.down();
await page.mouse.move(h1.x - 30, h1.y + 130, { steps: 5 }); await page.mouse.up();
await page.locator('.loupe-syl-toggle').click();
await page.waitForTimeout(900);
console.log('dragged, panel open: loupe', JSON.stringify(await page.locator('.loupe').boundingBox()), 'panel', JSON.stringify(await page.locator('.loupe-panel').boundingBox()));
await page.screenshot({ path: 'step2-desktop-1400-dragged-open.png' });
await browser.close();
